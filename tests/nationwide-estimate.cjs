const fs=require('node:fs'), assert=require('node:assert/strict');
const {chromium}=require('playwright');
const base=process.env.QA_BASE_URL||'http://127.0.0.1:8765';
(async()=>{
 const browser=await chromium.launch({headless:true});
 fs.mkdirSync('qa-output',{recursive:true});
 for(const width of [390,1440]){
  const page=await browser.newPage({viewport:{width,height:900}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'/funeral-cost-calculator.html');
  await page.waitForFunction(()=>document.querySelector('#nationwide-status').textContent.includes('가격은'));
  await page.evaluate(()=>setStep(3));
  await page.getByRole('button',{name:'서울',exact:true}).click();
  await page.selectOption('#subregionSelect','강남구');
  const hall=await page.locator('#hallSelect option').nth(1).getAttribute('value');
  await page.evaluate(n=>chooseHall(n),hall);
  await page.waitForTimeout(100);
  const rows=page.locator('[id^="facility-row-"]');
  assert.ok(await rows.count()>0,'hall price rows available');
  await rows.first().check();
  let values=await page.evaluate(()=>({total:calcData().total,external:calcData().external,hall:Number(document.getElementById('hallCost').value)}));
  assert.ok(values.hall>0);assert.equal(values.external,values.hall);
  await page.locator('#facility-qty-0').fill('3');
  const price=await page.evaluate(()=>calcData().external);
  const label=await page.locator('.facility-price').first().textContent();
  const unitPrice=Number(label.match(/([\d,]+)원/)[1].replaceAll(',',''));
  assert.equal(price,unitPrice*3,'unit price times quantity exactly');
  await page.screenshot({path:'qa-output/hall-'+width+'.png',fullPage:true});
  await page.locator('#hall-manual').check();
  assert.ok((await page.locator('#estimate-pending').textContent()).includes('직접 입력 금액 미확인'));
  await page.locator('#hallCost').fill('321000');
  await page.locator('#hall-manual-source').fill('검수용 시설 확인');
  await page.evaluate(()=>setStep(4));
  await page.locator('[data-field=burialType][data-value=화장]').click();
  await page.evaluate(()=>setStep(5));
  await page.selectOption('#crem-facility','고성군공설화장장');
  await page.selectOption('#crem-rate','0');
  assert.equal(await page.inputValue('#cremationCost'),'400000');
  assert.equal(await page.evaluate(()=>calcData().external),721000);
  await page.evaluate(()=>setStep(4));
  await page.locator('[data-field=burialType][data-value=매장]').click();
  assert.equal(await page.evaluate(()=>calcData().external),321000);
  await page.locator('[data-field=burialType][data-value=화장]').click();
  await page.evaluate(()=>setStep(5));
  await page.selectOption('#crem-facility','공주나래원');
  assert.equal(await page.inputValue('#cremationCost'),'');
  await page.screenshot({path:'qa-output/cremation-'+width+'.png',fullPage:true});
  await page.evaluate(()=>setStep(11));
  const text=await page.evaluate(()=>summaryText());
  assert.ok(text.includes('항목별 산출내역'));assert.ok(text.includes('미확인 비용'));assert.ok(text.includes('검수용 시설 확인'));
  assert.ok(await page.locator('#estimate-pending').isVisible());
  assert.ok((await page.locator('#estimate-context').textContent()).includes(hall));
  assert.ok((await page.locator('#estimate-context').textContent()).includes('작성일')); 
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'qa-output/estimate-'+width+'.png',fullPage:true});
  await page.emulateMedia({media:'print'});
  await page.pdf({path:'qa-output/estimate-'+width+'.pdf',format:'A4'});
  await page.emulateMedia({media:'screen'});
  await page.evaluate(()=>setStep(3));
  await page.selectOption('#subregionSelect','강동구');
  assert.equal(await page.inputValue('#hallCost'),'');
  assert.equal(await page.evaluate(()=>calcData().external),0);
  await page.locator('#hall-manual').check();
  await page.locator('#hallCost').fill('-9999');
  assert.equal(await page.evaluate(()=>calcData().external),0,'negative cost is clamped');
  assert.deepEqual(errors,[],'no browser runtime errors');
  await page.close();
 }
 const page=await browser.newPage();
 await page.route('**/data/*.json',r=>r.abort());
 await page.goto(base+'/funeral-cost-calculator.html');
 await page.waitForFunction(()=>document.querySelector('#nationwide-status').textContent.includes('실패'));
 assert.ok((await page.locator('#estimate-pending').textContent()).includes('연결 실패'));
 await browser.close();console.log('Nationwide estimate QA passed: desktop, mobile, calculations, stale facility reset, print and failure fallback.');
})().catch(e=>{console.error(e);process.exit(1)});
